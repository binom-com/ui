// Builds dist/ from tokens/tokens.json and src/*.css. No dependencies: `node scripts/build.mjs [outDir]`.
// dist/ is committed (apps install from GitHub without building); a test checks it matches a fresh build.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = process.argv[2] ?? join(root, 'dist');
const tokens = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const read = (p) => readFileSync(join(root, p), 'utf8');

const HEADER = '/* Generated by @binom/ui scripts/build.mjs from tokens/tokens.json. Do not edit: change the tokens and rebuild. */\n';
const DARK_SYSTEM = "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {";

/** [name, token] pairs of one set, in file order (groups only organise). */
const entries = (set) => Object.values(tokens[set]).flatMap((group) => Object.entries(group));

/** `{group.name}` references become `var(--name)`; everything else is literal. */
const css = (value) => value.replace(/\{[a-z]+\.([a-z0-9-]+)\}/g, 'var(--$1)');

function declarations(set, indent) {
  return entries(set)
    .map(([name, t]) => (t.$description ? `${indent}/* ${t.$description} */\n` : '') + `${indent}--${name}: ${css(t.$value)};`)
    .join('\n');
}

const dark = (indent) => `${declarations('dark', indent)}\n${indent}color-scheme: dark;`;

const tokensCss =
  HEADER +
  '/* Light theme and the tokens both themes share. */\n' +
  `:root {\n${declarations('core', '  ')}\n${declarations('light', '  ')}\n  color-scheme: light;\n}\n\n` +
  "/* Dark theme, picked in the app's settings (`data-theme` on <html>)... */\n" +
  `:root[data-theme='dark'] {\n${dark('  ')}\n}\n\n` +
  '/* ...or by the system, unless the app forces light. */\n' +
  `${DARK_SYSTEM}\n${dark('    ')}\n  }\n}\n\n` +
  '/* A mouse or trackpad needs no finger-sized targets: compact controls are smaller there. */\n' +
  `@media (pointer: fine) {\n  :root {\n${declarations('pointer-fine', '    ')}\n  }\n}\n\n` +
  '/* «Less motion» in the system settings turns every transition off. */\n' +
  `@media (prefers-reduced-motion: reduce) {\n  :root {\n${declarations('reduced-motion', '    ')}\n  }\n}\n`;

const fontsCss = HEADER + read('src/fonts.css');
const baseCss = HEADER + read('src/base.css');
const strip = (s) => s.slice(HEADER.length);
const themeCss =
  HEADER + '/* Everything for a plain-CSS app: fonts, tokens, base element rules. Import it before the app\'s own CSS. */\n\n' +
  strip(fontsCss) + '\n' + strip(tokensCss) + '\n' + strip(baseCss);

// Tailwind 4: the light/shared tokens become theme variables (utilities like bg-page, text-muted, rounded-xl,
// shadow-dialog); `static` emits them all even when no utility uses them, since app CSS reads them too. The dark,
// pointer and motion blocks stay unlayered so they win over Tailwind's theme layer. Tailwind's own palette is kept.
// Shadows are the exception: Tailwind copies a shadow's value into its utility, so the dark one would never apply.
// They stay plain variables and get their own `shadow-*` utilities that read the variable.
const darkAndRest = strip(tokensCss).slice(strip(tokensCss).indexOf("/* Dark theme"));
const fontToken = entries('core').find(([n]) => n === 'font')[1].$value;
const isShadow = ([name]) => name.startsWith('shadow-');
const lines = (pairs, indent) =>
  pairs.map(([name, t]) => (t.$description ? `${indent}/* ${t.$description} */\n` : '') + `${indent}--${name}: ${css(t.$value)};`).join('\n');
const themed = [...entries('core'), ...entries('light')];
const tailwindCss =
  HEADER + "@import './fonts.css';\n\n" +
  `@theme static {\n${lines(themed.filter((e) => !isShadow(e)), '  ')}\n  --font-sans: ${fontToken};\n}\n\n` +
  `:root {\n${lines(themed.filter(isShadow), '  ')}\n  color-scheme: light;\n}\n\n` +
  themed.filter(isShadow).map(([name]) => `@utility ${name} {\n  box-shadow: var(--${name});\n}\n`).join('\n') + '\n' +
  darkAndRest;

// Material UI 5 needs literal colours (it computes alpha and contrast): resolve references per mode.
function resolved(mode) {
  const map = new Map([...entries('core'), ...entries(mode)].map(([n, t]) => [n, t.$value]));
  const get = (n) => {
    const v = map.get(n);
    const m = /^\{[a-z]+\.([a-z0-9-]+)\}$/.exec(v);
    return m ? get(m[1]) : v;
  };
  return get;
}
function muiOptions(mode) {
  const t = resolved(mode);
  return {
    palette: {
      mode,
      primary: { main: t('color-accent'), contrastText: t('color-on-accent') },
      error: { main: t('color-danger') },
      background: { default: t('color-page'), paper: t('color-bg') },
      text: { primary: t('color-text'), secondary: t('color-muted') },
      divider: t('color-border'),
    },
    typography: { fontFamily: t('font') },
    shape: { borderRadius: parseInt(t('radius'), 10) },
  };
}
const muiJs =
  HEADER.replace('/*', '//').replace(' */', '') +
  '/** Material UI 5 theme options from the Binom tokens: `createTheme(createBinomTheme(mode))`. Also import\n' +
  ' * `@binom/ui/fonts.css` and `@binom/ui/tokens.css` so non-MUI parts read the same tokens. */\n' +
  `const OPTIONS = ${JSON.stringify({ light: muiOptions('light'), dark: muiOptions('dark') }, null, 2)};\n\n` +
  "export function createBinomTheme(mode = 'light') {\n" +
  "  if (mode !== 'light' && mode !== 'dark') throw new Error(`@binom/ui: unknown mode ${mode}`);\n" +
  '  return structuredClone(OPTIONS[mode]);\n}\n';
const muiDts =
  "import type { ThemeOptions } from '@mui/material/styles';\n\n" +
  '/** Material UI 5 theme options from the Binom tokens: `createTheme(createBinomTheme(mode))`. */\n' +
  "export function createBinomTheme(mode?: 'light' | 'dark'): ThemeOptions;\n";

mkdirSync(out, { recursive: true });
const files = {
  'tokens.css': tokensCss, 'fonts.css': fontsCss, 'base.css': baseCss, 'theme.css': themeCss,
  'tailwind.css': tailwindCss, 'mui.js': muiJs, 'mui.d.ts': muiDts,
};
for (const [name, content] of Object.entries(files)) writeFileSync(join(out, name), content);
